/* Scripts */
import themeJSON from '../../tokens/theme.json' with { type: 'json' }; // generated by scripts/tokens-generate.js

/* Build favicons */
const faviconsJson = themeJSON.favicon;
const faviconsKeys = Object.keys(faviconsJson).filter((key) => key.includes('src-'));
const faviconsList = [];

faviconsKeys.forEach((favicon) => {
	const current = faviconsJson[favicon];
	const key = favicon.replace('src-', '');

	// Set type attribute
	let type = 'image/png';
	if (current.includes('.svg')) {
		type = 'image/svg+xml';
	} else if (current.includes('.ico')) {
		type = 'image/x-icon';
	}

	const config = {
		isHead: faviconsJson[`head-${key}`] ?? false,
		isManifest: faviconsJson[`manifest-${key}`] ?? false,
		purpose: faviconsJson[`purpose-${key}`] ?? 'any',
		rel: current.includes('apple-touch-icon') ? 'apple-touch-icon' : 'icon',
		src: current,
		size: faviconsJson[`size-${key}`],
		sizes: faviconsJson[`sizes-${key}`] ?? faviconsJson[`size-${key}`],
		type: type,
	};

	faviconsList.push(config);
});

export const favicons = faviconsList;
