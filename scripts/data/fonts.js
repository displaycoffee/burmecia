/* Scripts */
import themeJSON from '../../tokens/theme.json' with { type: 'json' }; // generated by scripts/tokens-generate.js

/* Build font families */
const fontsJson = themeJSON.font;
const fontsKeys = Object.keys(fontsJson).filter((key) => key.includes('src-'));
const fontsList = [];

fontsKeys.forEach((font) => {
	const current = fontsJson[font];
	const key = font.includes('header') ? 'header' : 'body';
	const weight = font.includes('bold') ? 700 : 400;
	const srcSplit = current.split('.');

	// Preload the non-italic file each family uses first: regular for body text, and the header weight token for headers
	const preloadWeight = key === 'header' ? fontsJson['weight-header'] : 400;
	const isPreload = !font.includes('italic') && weight === preloadWeight;

	const config = {
		display: 'swap',
		ext: srcSplit[srcSplit.length - 1],
		family: fontsJson[`name-${key}`],
		preload: isPreload,
		src: current,
		style: font.includes('italic') ? 'italic' : 'normal',
		weight: weight,
	};

	fontsList.push(config);
});

export const fonts = fontsList;
