/* Scripts */
import themeJSON from '../../tokens/theme.json' with { type: 'json' }; // generated by scripts/tokens-generate.js

/* Build fallback font families */
const fallbacksJson = themeJSON.fallback;
const fallbacksKeys = Object.keys(fallbacksJson).filter((key) => key.includes('src-'));
const fallbacksList = [];

fallbacksKeys.forEach((fallback) => {
	const current = fallbacksJson[fallback];
	const key = fallback.includes('header') ? 'header' : 'body';

	const config = {
		family: fallbacksJson[`name-${key}`],
		size: fallbacksJson[`size-${key}`],
		src: current,
	};

	fallbacksList.push(config);
});

export const fallbacks = fallbacksList;
